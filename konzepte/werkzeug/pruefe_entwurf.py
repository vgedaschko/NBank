#!/usr/bin/env python3
"""Prüft eine fertige Entwurfsmappe (pptx aus entwurf.cjs) von außen. Liest nur, ändert nichts.

Aufruf:
    python3 pruefe_entwurf.py DATEI.pptx [--text]      --text listet zusätzlich den Text jeder Folie

Geprüft wird (Fehler: Rückgabewert 1; Hinweise brechen nicht ab):
  Schrift      nur Montserrat und Work Sans (Folien, Diagramme); keine Größe unter 10 pt; Tabellenzellen mindestens 12 pt
  Rollen       Hinweiskasten in Work Sans Light 12 pt (G8); Stichpunkte in 14 pt (G9); Fließtext (Text, Planlegende, Kommentar …) mindestens 14 pt
  Sprache      kein Gedankenstrich als Einschub (Halbgeviertstrich zwischen Leerzeichen, Geviertstrich); Begriffe der Änderungsrunde
               (Hinweis bei „Baukosten“, „nötige Miete“, „Förderregeln“, „Annuität“ ohne „über 30 Jahre“); kein „undefined“ oder „NaN“
  Datei        keine Werkzeugnamen und keine Pfade aus Arbeitsordnern in irgendeinem Teil der Datei; jedes Diagramm hat
               einen Alternativtext; keine Sprechernotizen; keine Folie als Bild
Braucht nur die Standardbibliothek von Python 3.9 oder neuer.
"""
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

A = "{http://schemas.openxmlformats.org/drawingml/2006/main}"
P = "{http://schemas.openxmlformats.org/presentationml/2006/main}"

SCHRIFTEN = ("Montserrat", "Work Sans")
FLIESSTEXT = re.compile(r"^(Kommentar|Planlegende|Aufzählung|Vorspann|Untertitel|Text|Links Text|Rechts Text|Kennzahl( \d)? Text|Achtung Text|Hero-Text)")
HINWEIS = re.compile(r"^Hinweiskasten.*Text$")
VERBOTEN_DATEI = [
    (re.compile(r"pptxgenjs|python-pptx|LibreOffice|OpenOffice|generated by|created with|erzeugt mit|erstellt mit|KI-generiert|AI-generated", re.I), "Werkzeugname"),
    (re.compile(r"/tmp/|/root/|/home/|\.lohome", re.I), "Pfad aus einem Arbeitsordner"),
]
BEGRIFFE = [
    (re.compile(r"Baukosten", re.I), "„Herstellungskosten“ statt „Baukosten“ (G3)"),
    (re.compile(r"nötige(n)? Miete", re.I), "„kostendeckende Anfangsmiete“ statt „nötige Miete“ (G4)"),
    (re.compile(r"Förderregeln", re.I), "„Förderkonditionen“ statt „Förderregeln“ (G5)"),
]
EINSCHUB = re.compile(r"\s[–—]\s|—")
CLAIMS = [re.compile(r"Aus Ihrer guten Idee – machen wir den besten Plan", re.I), re.compile(r"Ihre PGN – ")]


def folien(z):
    namen = [n for n in z.namelist() if re.fullmatch(r"ppt/slides/slide\d+\.xml", n)]
    return sorted(namen, key=lambda n: int(re.search(r"(\d+)\.xml$", n).group(1)))


def absaetze(elem):
    for p in elem.iter(A + "p"):
        laeufe = [(r.find(A + "rPr"), (r.find(A + "t").text or "")) for r in p.iter(A + "r") if r.find(A + "t") is not None]
        yield "".join(t for _, t in laeufe), laeufe


def main(argv):
    if not argv or argv[0].startswith("-"):
        print(__doc__)
        return 2
    datei, mit_text = argv[0], "--text" in argv
    fehler, hinweise = [], []
    z = zipfile.ZipFile(datei)

    for teil in z.namelist():
        if not teil.endswith((".xml", ".rels")):
            continue
        roh = z.read(teil).decode("utf-8", "replace")
        for muster, was in VERBOTEN_DATEI:
            m = muster.search(roh)
            if m:
                fehler.append(f"{teil}: {was} „{m.group(0)}“ in der Datei")
        if teil.startswith("ppt/charts/") and teil.endswith(".xml"):
            for f in set(re.findall(r'typeface="([^"]+)"', roh)):
                if not f.startswith(SCHRIFTEN) and not f.startswith("+"):
                    fehler.append(f"{teil}: Schrift „{f}“ im Diagramm")
            for sz in set(re.findall(r'<a:defRPr[^>]*\bsz="(\d+)"', roh)):
                if int(sz) < 1000:
                    fehler.append(f"{teil}: {int(sz) / 100:g} pt im Diagramm, unter 10 pt")
    if any("notesSlide" in n for n in z.namelist()):
        fehler.append("Die Datei trägt Sprechernotizen.")

    for nr, teil in enumerate(folien(z), 1):
        wurzel = ET.fromstring(z.read(teil))
        texte = []
        for form in wurzel.iter():
            if form.tag not in (P + "sp", P + "graphicFrame", P + "pic"):
                continue
            cnv = form.find(".//" + P + "cNvPr")
            name = cnv.get("name", "") if cnv is not None else ""
            if form.tag == P + "pic":
                ext = form.find(".//" + A + "ext")
                if ext is not None and int(ext.get("cx", 0)) > 10 * 914400:
                    fehler.append(f"Folie {nr}: Bild „{name}“ fast so breit wie die Folie (Folie als Bild?)")
                continue
            if form.tag == P + "graphicFrame" and form.find(".//{http://schemas.openxmlformats.org/drawingml/2006/chart}chart") is not None:
                if not (cnv is not None and (cnv.get("descr") or "").strip()):
                    fehler.append(f"Folie {nr}: Diagramm „{name}“ ohne Alternativtext")
            in_tabelle = form.tag == P + "graphicFrame"
            for text, laeufe in absaetze(form):
                if not text.strip():
                    continue
                texte.append((name, text))
                for rpr, t in laeufe:
                    if not t.strip() or rpr is None:
                        continue
                    latin = rpr.find(A + "latin")
                    schrift = latin.get("typeface") if latin is not None else None
                    sz = int(rpr.get("sz")) / 100 if rpr.get("sz") else None
                    if schrift and not schrift.startswith(SCHRIFTEN) and not schrift.startswith("+"):
                        fehler.append(f"Folie {nr}, „{name}“: Schrift „{schrift}“")
                    if sz is not None and sz < 10:
                        fehler.append(f"Folie {nr}, „{name}“: {sz:g} pt unter 10 pt")
                    if in_tabelle and sz is not None and sz < 12:
                        fehler.append(f"Folie {nr}, „{name}“: Tabellenzelle in {sz:g} pt, unter 12 pt")
                    if HINWEIS.match(name) and (schrift != "Work Sans Light" or sz != 12):
                        fehler.append(f"Folie {nr}, „{name}“: Hinweiskasten in {schrift} {sz} pt, verlangt Work Sans Light 12 pt (G8)")
                    if name.startswith("Stichpunkte") and schrift and schrift.startswith("Work Sans") and sz != 14:
                        fehler.append(f"Folie {nr}, „{name}“: Stichpunkt in {sz} pt, verlangt 14 pt (G9)")
                    if FLIESSTEXT.match(name) and schrift and schrift.startswith("Work Sans") and sz is not None and sz < 14:
                        fehler.append(f"Folie {nr}, „{name}“: Fließtext in {sz:g} pt, mindestens 14 pt (Name mit „Text“ heißt Fließtext; kleine Beschriftungen brauchen einen eigenen Namen)")
                glatt = text.replace(" ", " ")
                if EINSCHUB.search(glatt) and not any(c.search(glatt) for c in CLAIMS):
                    fehler.append(f"Folie {nr}, „{name}“: Gedankenstrich als Einschub: „{glatt}“")
                if re.search(r"\b(undefined|NaN)\b", glatt):
                    fehler.append(f"Folie {nr}, „{name}“: „undefined“ oder „NaN“ im Text")
                for muster, was in BEGRIFFE:
                    if muster.search(glatt):
                        hinweise.append(f"Folie {nr}, „{name}“: {was}: „{glatt}“")
                if re.search(r"Annuität", glatt) and not re.search(r"jährliche Annuität über 30 Jahre", glatt):
                    hinweise.append(f"Folie {nr}, „{name}“: Begriff „jährliche Annuität über 30 Jahre“ (G6) prüfen: „{glatt}“")
        if mit_text:
            print(f"--- Folie {nr}")
            for name, text in texte:
                print(f"  [{name}] {text}")

    for h in hinweise:
        print("Hinweis · " + h)
    for f in fehler:
        print("Fehler · " + f)
    print(f"{datei}: {len(folien(z))} Folien · {len(fehler)} Fehler · {len(hinweise)} Hinweise")
    return 1 if fehler else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
